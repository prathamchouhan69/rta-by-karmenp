export type TranslationKey = keyof typeof strings;

export function translate(lang: Lang, key: TranslationKey, vars?: Record<string, string | number>): string {
  const entry = strings[key];
  let value: string = entry ? entry[lang] : key;
  if (vars) for (const [name, replacement] of Object.entries(vars)) value = value.replaceAll(`{${name}}`, String(replacement));
  return value;
}

export function allKeys(): TranslationKey[] {
  return Object.keys(strings) as TranslationKey[];
}
